// Adapter implements parser.LanguageAdapter for TypeScript and JavaScript.
type Adapter struct{}

// NewAdapter creates a new TypeScript/JavaScript language adapter.
func NewAdapter() *Adapter {
	return &Adapter{}
}

// ID returns the unique language identifier for this adapter.
func (a *Adapter) ID() string {
	return "typescript"
}

// FileExtensions returns the file extensions recognized by this adapter.
func (a *Adapter) FileExtensions() []string {
	return []string{
		".ts", ".tsx", ".js", ".jsx",
		".mjs", ".cjs", ".mts", ".cts",
	}
}

// IsGenerated determines whether a file was auto-generated by inspecting
// standard TypeScript/JavaScript file suffixes and code generation headers.
func (a *Adapter) IsGenerated(filePath string, header []byte) bool {
	lower := strings.ToLower(filePath)
	base := filepath.Base(lower)

	if strings.HasSuffix(base, ".d.ts") ||
		strings.HasSuffix(base, ".generated.ts") ||
		strings.HasSuffix(base, ".generated.js") ||
		strings.HasSuffix(base, ".gen.ts") ||
		strings.HasSuffix(base, ".gen.js") ||
		strings.HasSuffix(base, ".g.ts") ||
		strings.HasSuffix(base, ".g.js") {
		return true
	}

	headerLower := bytes.ToLower(header)
	if bytes.Contains(headerLower, []byte("@generated")) ||
		bytes.Contains(headerLower, []byte("code generated")) ||
		bytes.Contains(headerLower, []byte("generated by")) ||
		bytes.Contains(headerLower, []byte("auto-generated")) ||
		bytes.Contains(headerLower, []byte("do not edit")) {
		return true
	}

	return false
}

type scopeEntry struct {
	title       string
	closeOffset int
}

// tokenMatcher resolves bracket pairs within a token stream.
type tokenMatcher struct {
	tokens []Token
}

func newTokenMatcher(tokens []Token) tokenMatcher {
	return tokenMatcher{tokens: tokens}
}

// closingFor maps an opening bracket token to its closing token.
var closingFor = map[string]string{"(": ")", "[": "]", "{": "}", "<": ">"}

// closing returns the index of the token closing the bracket at openIdx, or -1
// when the stream ends first. Generic argument lists are included so a typed
// call such as `expect<number>(x)` reads as one call; JSX tags never leave a
// standalone `<` token behind.
func (m tokenMatcher) closing(openIdx int) int {
	if openIdx < 0 || openIdx >= len(m.tokens) {
		return -1
	}
	open := m.tokens[openIdx].Value
	closeTok, ok := closingFor[open]
	if !ok {
		return -1
	}
	depth := 0
	for k := openIdx; k < len(m.tokens); k++ {
		switch m.tokens[k].Value {
		case open:
			depth++
		case closeTok:
			depth--
			if depth == 0 {
				return k
			}
		}
	}
	return -1
}

// testCallModifiers lists the members that may sit between an it/test/fit
// callable and its title call. The value reports whether the member consumes an
// operand first, as it.each([...]) and it.skipIf(cond) do.
var testCallModifiers = map[string]bool{
	"each":       true,
	"skipIf":     true,
	"runIf":      true,
	"if":         true,
	"only":       false,
	"fails":      false,
	"concurrent": false,
	"sequential": false,
	"serial":     false,
	"parallel":   false,
	"retries":    false,
}

// testCallNonDeclarations lists members of it/test/fit that never declare a
// test: hooks, fixtures, configuration, steps and declaration-level skips. A
// member absent from both tables is rejected too, so an unknown call shape can
// never manufacture a test unit.
var testCallNonDeclarations = map[string]bool{
	"skip": true, "todo": true, "fixme": true, "describe": true, "step": true,
	"beforeEach": true, "afterEach": true, "beforeAll": true, "afterAll": true,
	"use": true, "setTimeout": true, "slow": true, "info": true,
	"extend": true, "configure": true, "fail": true,
}

// scopeCallModifiers lists the members that may sit between a describe-style
// callable and its title. `configure` is deliberately absent: it configures a
// suite rather than opening one.
var scopeCallModifiers = map[string]bool{
	"each": true, "only": false, "skip": false, "todo": false, "fixme": false,
	"concurrent": false, "sequential": false, "serial": false, "parallel": false,
	"retries": false,
}

// callArgs walks the members chained on the callable at root and returns the
// index of the token opening its title argument list.
func callArgs(tokens []Token, root int, modifiers map[string]bool, rejected map[string]bool, matcher tokenMatcher) (int, bool) {
	curr := root + 1
	for curr+1 < len(tokens) && (tokens[curr].Value == "." || tokens[curr].Value == "?.") {
		member := tokens[curr+1]
		if member.Type != TokenIdent && member.Type != TokenKeyword {
			return -1, false
		}
		if rejected[member.Value] {
			return -1, false
		}
		takesOperand, allowed := modifiers[member.Value]
		if !allowed {
			return -1, false
		}
		curr += 2
		if takesOperand {
			next, ok := skipModifierOperand(tokens, curr, matcher)
			if !ok {
				return -1, false
			}
			curr = next
		}
	}
	if curr < len(tokens) && tokens[curr].Value == "(" {
		return curr, true
	}
	return -1, false
}

// skipModifierOperand advances past the operand of a curried modifier: an
// argument list, an array literal, or a tagged template table.
func skipModifierOperand(tokens []Token, curr int, matcher tokenMatcher) (int, bool) {
	if curr >= len(tokens) {
		return 0, false
	}
	if tokens[curr].Type == TokenTemplate {
		return curr + 1, true
	}
	if tokens[curr].Value == "(" || tokens[curr].Value == "[" {
		closeIdx := matcher.closing(curr)
		if closeIdx == -1 {
			return 0, false
		}
		return closeIdx + 1, true
	}
	return 0, false
}

// scopeRootIndex reports the token index introducing a naming scope when the
// token at i is a describe-style callable.
func scopeRootIndex(tokens []Token, i, n int, tok Token, prevTokVal string) (int, bool) {
	if prevTokVal == "." || prevTokVal == "?." || prevTokVal == "function" {
		return -1, false
	}
	switch tok.Value {
	case "describe", "context", "suite":
		return i, true
	case "test":
		if i+2 < n && tokens[i+1].Value == "." && tokens[i+2].Value == "describe" {
			return i + 2, true
		}
	}
	return -1, false
}

// isTitleLiteral reports whether tok is a literal test title.
func isTitleLiteral(tok Token) bool {
	return tok.Type == TokenString || tok.Type == TokenTemplate
}

// isFunctionLiteralAt reports whether a function literal — `function`,
// `async function`, an arrow, or an async arrow — starts at tokens[s], with
// the literal confined to tokens before limit.
func isFunctionLiteralAt(tokens []Token, s int, limit int, matcher tokenMatcher) bool {
	if s >= limit {
		return false
	}
	if tokens[s].Value == "async" {
		s++
		if s >= limit {
			return false
		}
	}
	switch {
	case tokens[s].Value == "function":
		return true
	case tokens[s].Type == TokenIdent && s+1 < limit && tokens[s+1].Value == "=>":
		return true
	case tokens[s].Value == "(":
		closeIdx := matcher.closing(s)
		if closeIdx == -1 || closeIdx >= limit {
			return false
		}
		if closeIdx+1 < limit && tokens[closeIdx+1].Value == "=>" {
			return true
		}
		// Return-type annotation: (a): void => ...
		if closeIdx+1 < limit && tokens[closeIdx+1].Value == ":" {
			for k := closeIdx + 2; k < limit; k++ {
				if tokens[k].Value == "=>" {
					return true
				}
				if tokens[k].Value == "," || tokens[k].Value == ";" {
					return false
				}
			}
		}
	}
	return false
}

// topLevelArgCommas returns the indexes of the commas that separate the
// arguments of the call whose argument list spans (openIdx, closeIdx).
func topLevelArgCommas(tokens []Token, openIdx, closeIdx int) []int {
	var commas []int
	depth := 0
	for k := openIdx + 1; k < closeIdx; k++ {
		switch tokens[k].Value {
		case "(", "[", "{":
			depth++
		case ")", "]", "}":
			depth--
		case ",":
			if depth == 0 {
				commas = append(commas, k)
			}
		}
	}
	return commas
}

// dynamicTitleCallback reports the index of the comma ending a non-literal
// title when the call is shaped like a declaration: the second or the last
// argument is a function literal. test(1, 2) and fit([1, 2]) stay rejected.
func dynamicTitleCallback(tokens []Token, openIdx, closeIdx int, matcher tokenMatcher) (int, bool) {
	commas := topLevelArgCommas(tokens, openIdx, closeIdx)
	if len(commas) == 0 {
		return -1, false
	}
	titleIdx := openIdx + 1
	if titleIdx >= commas[0] {
		return -1, false
	}
	if isFunctionLiteralAt(tokens, titleIdx, commas[0], matcher) {
		return -1, false
	}
	second := commas[0] + 1
	if isFunctionLiteralAt(tokens, second, closeIdx, matcher) {
		return commas[0], true
	}
	last := commas[len(commas)-1] + 1
	if isFunctionLiteralAt(tokens, last, closeIdx, matcher) {
		return commas[0], true
	}
	return -1, false
}

// fitIsBound reports whether the file binds the identifier fit itself: a
// declaration, an import (default, named, aliased-to, namespace) or a
// require/destructuring pattern. The Jasmine/Jest global fit is never declared
// in the file, so any binding means a call to fit is a utility, not a test.
func fitIsBound(tokens []Token, matcher tokenMatcher) bool {
	for k, tok := range tokens {
		if tok.Value != "fit" || tok.Type != TokenIdent || k == 0 {
			continue
		}
		switch tokens[k-1].Value {
		case "const", "let", "var", "function", "class", "import", "as":
			return true
		case ".", "?.":
			continue
		}
		// Inside a destructuring/import brace list: find the unmatched `{`.
		depth := 0
		for b := k - 1; b >= 0; b-- {
			if tokens[b].Value == "}" {
				depth++
			} else if tokens[b].Value == "{" {
				if depth > 0 {
					depth--
					continue
				}
				closeIdx := matcher.closing(b)
				prev := ""
				if b > 0 {
					prev = tokens[b-1].Value
				}
				next := ""
				if closeIdx != -1 && closeIdx+1 < len(tokens) {
					next = tokens[closeIdx+1].Value
				}
				if prev == "import" || prev == "const" || prev == "let" || prev == "var" ||
					(prev == "," && next == "from") || next == "from" {
					return true
				}
				break
			}
		}
	}
	return false
}

// declaredLocally reports whether the file itself defines name as a function,
// class, or a variable initialised with a function literal. A call to such a
// name is not the framework's test declaration. `const test = base.extend(...)`
// is a framework fixture and does not count. A bound fit is always a utility.
// Applied to dynamic titles only.
func declaredLocally(tokens []Token, name string, matcher tokenMatcher) bool {
	if name == "fit" && fitIsBound(tokens, matcher) {
		return true
	}
	for k := 0; k+1 < len(tokens); k++ {
		if tokens[k+1].Value != name || tokens[k+1].Type != TokenIdent {
			continue
		}
		switch tokens[k].Value {
		case "function", "class":
			return true
		case "const", "let", "var":
			if k+3 < len(tokens) && tokens[k+2].Value == "=" && isFunctionLiteralAt(tokens, k+3, len(tokens), matcher) {
				return true
			}
		}
	}
	return false
}

func isSpaceByte(c byte) bool {
	return c == ' ' || c == '\t' || c == '\r' || c == '\n'
}

// bodyStartLine returns the 1-based line holding the first byte of the body that
// follows the title comma. Rule authors map offsets inside RawBody back to the
// source with it, so leading whitespace and multi-line declarations are skipped.
func bodyStartLine(src string, tokens []Token, commaIdx, bodyEndOffset int) int {
	line := tokens[commaIdx].Line
	for k := tokens[commaIdx].Offset + 1; k < bodyEndOffset && k < len(src); k++ {
		if !isSpaceByte(src[k]) {
			break
		}
		if src[k] == '\n' {
			line++
		}
	}
	return line
}

func unquoteArg(src string, tok Token) string {
	val := tok.Value
	if tok.Type == TokenString && len(val) >= 2 {
		q := val[0]
		if q == '\'' || q == '"' {
			inner := val[1 : len(val)-1]
			if q == '\'' {
				inner = strings.ReplaceAll(inner, `\'`, `'`)
			} else {
				inner = strings.ReplaceAll(inner, `\"`, `"`)
			}
			return inner
		}
	}
	if tok.Type == TokenTemplate && len(val) >= 2 && val[0] == '`' && val[len(val)-1] == '`' {
		return val[1 : len(val)-1]
	}
	return val
}

// LocateTests extracts test units from TypeScript and JavaScript source code.
func (a *Adapter) LocateTests(source []byte, filePath string) ([]parser.TestUnit, error) {
	src := string(source)
	ext := strings.ToLower(filepath.Ext(filePath))
	enableJSX := ext == ".tsx" || ext == ".jsx" || ext == ".js"
	lexer := NewLexerWithJSX(src, enableJSX)
	tokens := lexer.Tokenize()
	if err := lexer.scanError(); err != nil {
		return nil, err
	}

	n := len(tokens)
	if n == 0 {
		return nil, nil
	}
	matcher := newTokenMatcher(tokens)
	facts := analyzeFile(src, tokens)

	var units []parser.TestUnit
	var scopeStack []scopeEntry

	for i := 0; i < n; i++ {
		tok := tokens[i]

		// Pop expired scopes
		for len(scopeStack) > 0 && tok.Offset >= scopeStack[len(scopeStack)-1].closeOffset {
			scopeStack = scopeStack[:len(scopeStack)-1]
		}

		prevTokVal := ""
		if i > 0 {
			prevTokVal = tokens[i-1].Value
		}

		// Check for describe / context / suite / test.describe scopes
		if scopeIdx, ok := scopeRootIndex(tokens, i, n, tok, prevTokVal); ok {
			openIdx, isCall := callArgs(tokens, scopeIdx, scopeCallModifiers, nil, matcher)
			closeParen := -1
			if isCall {
				closeParen = matcher.closing(openIdx)
			}
			// `describe(args) {` is a method definition, not a scope.
			if closeParen != -1 && (closeParen+1 >= n || tokens[closeParen+1].Value != "{") {
				titleIdx := openIdx + 1
				if titleIdx < closeParen {
					title := unquoteArg(src, tokens[titleIdx])
					for b := titleIdx + 1; b < closeParen; b++ {
						if tokens[b].Value != "{" {
							continue
						}
						if braceClose := matcher.closing(b); braceClose != -1 {
							scopeStack = append(scopeStack, scopeEntry{
								title:       title,
								closeOffset: tokens[braceClose].Offset + 1,
							})
						}
						break
					}
				}
			}
		}

		// Check for test unit declarations: it, test, fit
		if tok.Value == "it" || tok.Value == "test" || tok.Value == "fit" || tok.Value == "specify" {
			if prevTokVal == "." || prevTokVal == "?." || prevTokVal == "function" {
				continue
			}
			openIdx, ok := callArgs(tokens, i, testCallModifiers, testCallNonDeclarations, matcher)
			if !ok {
				continue
			}
			closeParen := matcher.closing(openIdx)
			if closeParen == -1 {
				continue
			}
			// `name(args) {` is an object-literal or class method, not a call.
			if closeParen+1 < n && tokens[closeParen+1].Value == "{" {
				continue
			}
			titleIdx := openIdx + 1
			if titleIdx >= closeParen {
				continue
			}
			commaIdx := -1
			dynamicTitle := false
			if isTitleLiteral(tokens[titleIdx]) {
				if commas := topLevelArgCommas(tokens, openIdx, closeParen); len(commas) > 0 {
					commaIdx = commas[0]
					// A literal followed by more tokens (`'a' + suffix`) or a
					// template with interpolation is an expression, not a literal.
					dynamicTitle = commaIdx != titleIdx+1 ||
						(tokens[titleIdx].Type == TokenTemplate && strings.Contains(tokens[titleIdx].Value, "${"))
				}
			} else {
				// Identifier, member or call title: only a declaration shape
				// (function literal callback) and an unshadowed callee qualify.
				if declaredLocally(tokens, tok.Value, matcher) {
					continue
				}
				if c, ok := dynamicTitleCallback(tokens, openIdx, closeParen, matcher); ok {
					commaIdx = c
					dynamicTitle = true
				}
			}
			// A title without a callback body declares nothing to analyse.
			if commaIdx == -1 || commaIdx+1 >= closeParen {
				continue
			}

			bodyStartOffset := tokens[commaIdx].Offset + 1
			bodyEndOffset := tokens[closeParen].Offset
			rawBody := ""
			if bodyEndOffset >= bodyStartOffset && bodyEndOffset <= len(src) {
				rawBody = strings.TrimSpace(src[bodyStartOffset:bodyEndOffset])
			}

			// Build current scope
			var scopes []string
			for _, s := range scopeStack {
				scopes = append(scopes, s.title)
			}
			scopeStr := strings.Join(scopes, " > ")

			// Find assertions in this test unit
			classifiedAssertions := findAssertions(src, tokens, bodyStartOffset, bodyEndOffset, facts)
			var assertionStrings []string
			for _, a := range classifiedAssertions {
				assertionStrings = append(assertionStrings, a.Raw)
			}

			name := unquoteArg(src, tokens[titleIdx])
			meta := map[string]string{
				"body_start_line": strconv.Itoa(bodyStartLine(src, tokens, commaIdx, bodyEndOffset)),
			}
			if dynamicTitle {
				// Original title-expression source, not an evaluated value.
				name = strings.TrimSpace(src[tokens[titleIdx].Offset:tokens[commaIdx].Offset])
				meta["title_dynamic"] = "true"
			}

			units = append(units, parser.TestUnit{
				Name:       name,
				FilePath:   filePath,
				StartLine:  tok.Line,
				EndLine:    tokens[closeParen].Line,
				Kind:       "unit",
				RawBody:    rawBody,
				Assertions: assertionStrings,
				Scope:      scopeStr,
				Meta:       meta,
			})
		}
	}

	return units, nil
}
