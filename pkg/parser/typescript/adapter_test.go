func TestLocateTests_EdgeCases(t *testing.T) {
	src := `
		describe('level 1', () => {
			describe('level 2', () => {
				it('nested test', () => {
					expect(1).toBe(1);
				});
			});
		});

		it('arrow expression body', () => expect(42).toBe(42));

		function myAssertion(val) {
			expect(val).toBeGreaterThan(0);
		}

		it('calls helper', () => {
			myAssertion(10);
		});

		it('shadows helper', () => {
			const myAssertion = () => {};
			myAssertion();
		});
	`

	adapter := ts.NewAdapter()
	units, err := adapter.LocateTests([]byte(src), "edge.test.ts")
	if err != nil {
		t.Fatalf("LocateTests error: %v", err)
	}

	if len(units) != 4 {
		t.Fatalf("expected 4 units, got %d", len(units))
	}

	if units[0].Scope != "level 1 > level 2" {
		t.Errorf("expected Scope 'level 1 > level 2', got %q", units[0].Scope)
	}
	if len(units[0].Assertions) == 0 {
		t.Errorf("expected nested test to have assertions")
	}

	if units[1].Name != "arrow expression body" {
		t.Errorf("expected 'arrow expression body', got %q", units[1].Name)
	}
	if len(units[1].Assertions) == 0 {
		t.Errorf("expected arrow expression body to have assertions")
	}

	if units[2].Name != "calls helper" {
		t.Errorf("expected 'calls helper', got %q", units[2].Name)
	}
	if len(units[2].Assertions) == 0 {
		t.Errorf("expected 'calls helper' to have assertions")
	}

	if units[3].Name != "shadows helper" {
		t.Errorf("expected 'shadows helper', got %q", units[3].Name)
	}
	if len(units[3].Assertions) != 0 {
		t.Errorf("expected 'shadows helper' to have 0 assertions due to shadowing, got %v", units[3].Assertions)
	}
}

