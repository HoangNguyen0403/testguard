func TestAdapterContract(t *testing.T) {
	adapter := ts.NewAdapter()
	if adapter.ID() != "typescript" {
		t.Fatalf("expected ID 'typescript', got %q", adapter.ID())
	}

	expectedExts := map[string]bool{
		".ts": true, ".tsx": true, ".js": true, ".jsx": true,
		".mjs": true, ".cjs": true, ".mts": true, ".cts": true,
	}
	exts := adapter.FileExtensions()
	if len(exts) != len(expectedExts) {
		t.Errorf("expected %d extensions, got %d", len(expectedExts), len(exts))
	}
	for _, ext := range exts {
		if !expectedExts[ext] {
			t.Errorf("unexpected extension %q", ext)
		}
	}

	// Generated file checks
	if !adapter.IsGenerated("types.d.ts", nil) {
		t.Errorf("expected .d.ts to be generated")
	}
	if !adapter.IsGenerated("schema.generated.ts", nil) {
		t.Errorf("expected .generated.ts to be generated")
	}
	if !adapter.IsGenerated("api.g.ts", nil) {
		t.Errorf("expected .g.ts to be generated")
	}
	if !adapter.IsGenerated("file.ts", []byte("/* @generated by codegen */")) {
		t.Errorf("expected @generated header to be generated")
	}
	if adapter.IsGenerated("user.test.ts", []byte("import { it } from 'vitest';")) {
		t.Errorf("expected normal test not to be generated")
	}
}

func TestLocateTests_WeakTest(t *testing.T) {
	content, err := os.ReadFile("testdata/weak.test.ts")
	if err != nil {
		t.Fatalf("read weak.test.ts: %v", err)
	}

	adapter := ts.NewAdapter()
	units, err := adapter.LocateTests(content, "testdata/weak.test.ts")
	if err != nil {
		t.Fatalf("LocateTests error: %v", err)
	}

	if len(units) != 10 {
		t.Fatalf("expected 10 units, got %d", len(units))
	}

	expectedNames := []string{
		"bare expect without matcher",
		"existence only",
		"swallowed error path",
		"floating async assertion",
		"conditional assertion",
		"asserts the mock it just configured",
		"focused test left behind",
		"suppressed empty test",
		"parameterised %i",
		"template literal name",
	}

	for i, unit := range units {
		if unit.Name != expectedNames[i] {
			t.Errorf("unit[%d] expected Name %q, got %q", i, expectedNames[i], unit.Name)
		}
		if unit.Kind != "unit" {
			t.Errorf("unit[%d] expected Kind 'unit', got %q", i, unit.Kind)
		}
		if unit.Scope != "weak oracles an agent commonly emits" {
			t.Errorf("unit[%d] expected Scope 'weak oracles an agent commonly emits', got %q", i, unit.Scope)
		}
	}

	// Zero assertions: bare expect without matcher, suppressed empty test, parameterised %i, template literal name
	zeroAssertionIdxs := []int{0, 7, 8, 9}
	for _, idx := range zeroAssertionIdxs {
		if len(units[idx].Assertions) != 0 {
			t.Errorf("expected unit[%d] (%q) to have 0 assertions, got %v", idx, units[idx].Name, units[idx].Assertions)
		}
	}

	// The others must have >= 1 assertion
	nonZeroIdxs := []int{1, 2, 3, 4, 5, 6}
	for _, idx := range nonZeroIdxs {
		if len(units[idx].Assertions) == 0 {
			t.Errorf("expected unit[%d] (%q) to have real assertions, got 0", idx, units[idx].Name)
		}
	}
}

