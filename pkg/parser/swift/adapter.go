// Package swift provides a LanguageAdapter implementation for Swift test files (.swift).
package swift

import (
	"fmt"
	"strings"

	"github.com/HoangNguyen0403/testguard/pkg/parser"
)

// Adapter implements parser.LanguageAdapter for Swift files.
type Adapter struct{}

// NewAdapter creates and returns a new Swift LanguageAdapter.
func NewAdapter() *Adapter {
	return &Adapter{}
}

// ID returns the language identifier "swift".
func (a *Adapter) ID() string {
	return "swift"
}

// FileExtensions returns the file extensions handled by this adapter.
func (a *Adapter) FileExtensions() []string {
	return []string{".swift"}
}

// IsGenerated returns true if the file header indicates generated code.
func (a *Adapter) IsGenerated(filePath string, header []byte) bool {
	headerStr := strings.ToLower(string(header))
	return strings.Contains(headerStr, "generated by") ||
		strings.Contains(headerStr, "@generated") ||
		strings.Contains(headerStr, "do not edit")
}

// LocateTests parses a Swift source file and returns the list of detected test units.
// Input whose comments, strings, or brackets are lexically unbalanced is rejected
// with an error so the caller reports a parse failure instead of a partial scan.
func (a *Adapter) LocateTests(source []byte, filePath string) ([]parser.TestUnit, error) {
	src := string(source)
	if err := validateLexicalStructure(src); err != nil {
		return nil, err
	}
	lines := strings.Split(src, "\n")
	lineOffsets := computeLineOffsets(lines)

	helperMap := findAssertingHelpers(src)

	units := parseSwiftUnits(src, lineOffsets, filePath, helperMap)
	return units, nil
}

func computeLineOffsets(lines []string) []int {
	offsets := make([]int, len(lines))
	curr := 0
	for i, l := range lines {
		offsets[i] = curr
		curr += len(l) + 1 // +1 for '\n'
	}
	return offsets
}

func lineFromOffset(offsets []int, offset int) int {
	low, high := 0, len(offsets)-1
	result := 0
	for low <= high {
		mid := (low + high) / 2
		if offsets[mid] <= offset {
			result = mid
			low = mid + 1
		} else {
			high = mid - 1
		}
	}
	return result + 1 // 1-based
}

// skipCommentOrString advances past the comment, string, or backtick identifier
// that starts at src[i]. It reports the offset just past the construct and
// whether that construct was terminated, so LocateTests can reject input it
// cannot scan reliably. It returns (i, false) when src[i] starts none of them.
func skipCommentOrString(src string, i int) (int, bool) {
	n := len(src)
	if i >= n {
		return i, false
	}

	// Line comment: //
	if i+1 < n && src[i] == '/' && src[i+1] == '/' {
		j := i + 2
		for j < n && src[j] != '\n' {
			j++
		}
		return j, true
	}

	// Block comment: /* ... */ (nestable in Swift)
	if i+1 < n && src[i] == '/' && src[i+1] == '*' {
		j := i + 2
		depth := 1
		for j < n {
			if j+1 < n && src[j] == '/' && src[j+1] == '*' {
				depth++
				j += 2
				continue
			}
			if j+1 < n && src[j] == '*' && src[j+1] == '/' {
				depth--
				j += 2
				if depth == 0 {
					return j, true
				}
				continue
			}
			j++
		}
		return n, false
	}

	// Backtick identifier: `name`
	if src[i] == '`' {
		j := i + 1
		for j < n && src[j] != '`' && src[j] != '\n' {
			j++
		}
		if j < n && src[j] == '`' {
			return j + 1, true
		}
		return j, false
	}

	// Raw string: #"..."# or ##"..."## (and the multi-line #"""..."""# form).
	if src[i] == '#' {
		hashes := 0
		k := i
		for k < n && src[k] == '#' {
			hashes++
			k++
		}
		if k < n && src[k] == '"' {
			suffix := strings.Repeat("#", hashes)
			if k+2 < n && src[k+1] == '"' && src[k+2] == '"' {
				contentStart := k + 3
				idx := strings.Index(src[contentStart:], `"""`+suffix)
				if idx == -1 {
					return n, false
				}
				return contentStart + idx + 3 + hashes, true
			}
			idx := strings.Index(src[k+1:], `"`+suffix)
			if idx == -1 {
				return n, false
			}
			return k + 1 + idx + 1 + hashes, true
		}
		return i, false
	}

	if src[i] == '"' {
		return skipStringLiteral(src, i)
	}

	return i, false
}

// skipStringLiteral advances past a Swift string literal, honouring escapes,
// multi-line """...""" text, and \(...) interpolations whose expressions may
// contain nested strings, comments, and braces.
func skipStringLiteral(src string, i int) (int, bool) {
	n := len(src)
	multiline := i+2 < n && src[i+1] == '"' && src[i+2] == '"'
	j := i + 1
	if multiline {
		j = i + 3
	}
	for j < n {
		if src[j] == '\\' {
			if j+1 < n && src[j+1] == '(' {
				j = skipInterpolation(src, j+1)
				continue
			}
			j += 2
			continue
		}
		if multiline {
			if src[j] == '"' && j+2 < n && src[j+1] == '"' && src[j+2] == '"' {
				return j + 3, true
			}
		} else {
			if src[j] == '"' {
				return j + 1, true
			}
			if src[j] == '\n' {
				return j, false
			}
		}
		j++
	}
	return n, false
}

// skipInterpolation advances past the \(...) interpolation whose opening
// parenthesis is src[i], scanning nested strings and comments so a brace or
// parenthesis inside them does not end the expression early.
func skipInterpolation(src string, i int) int {
	n := len(src)
	depth := 0
	for i < n {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i + 1
			}
		}
		i++
	}
	return n
}

// skipCommentsAndStrings advances index i past any comment or string literal starting at src[i].
func skipCommentsAndStrings(src string, i int) int {
	end, _ := skipCommentOrString(src, i)
	return end
}

// validateLexicalStructure rejects a file whose comments, strings, or bracket
// delimiters are unbalanced. Swift is scanned lexically rather than with a full
// grammar, so this bound is what lets LocateTests fail closed instead of
// reporting a truncated unit list as a complete scan. Angle brackets and
// language constructs outside comments, strings, and brackets are not checked.
func validateLexicalStructure(src string) error {
	var stack []byte
	n := len(src)
	for i := 0; i < n; {
		if next, ok := skipCommentOrString(src, i); next != i {
			if !ok {
				return fmt.Errorf("swift: unterminated comment or string literal at offset %d", i)
			}
			i = next
			continue
		}
		switch src[i] {
		case '(', '[', '{':
			stack = append(stack, src[i])
		case ')', ']', '}':
			if len(stack) == 0 {
				return fmt.Errorf("swift: unexpected %q at offset %d", src[i], i)
			}
			open := stack[len(stack)-1]
			if (open == '(' && src[i] != ')') || (open == '[' && src[i] != ']') || (open == '{' && src[i] != '}') {
				return fmt.Errorf("swift: %q closes %q at offset %d", src[i], open, i)
			}
			stack = stack[:len(stack)-1]
		}
		i++
	}
	if len(stack) > 0 {
		return fmt.Errorf("swift: %d unclosed delimiter(s) at end of file", len(stack))
	}
	return nil
}

// findMatchingBrace returns the index of the '}' that closes the '{' at open,
// skipping comments, strings, and interpolations; it returns -1 when unmatched.
func findMatchingBrace(src string, open int) int {
	if open < 0 || open >= len(src) || src[open] != '{' {
		return -1
	}
	depth := 0
	n := len(src)
	for i := open; i < n; {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return i
			}
		}
		i++
	}
	return -1
}

// findMatchingParen returns the index of the ')' that closes the '(' at open,
// skipping comments, strings, and interpolations; it returns -1 when unmatched.
func findMatchingParen(src string, open int) int {
	if open < 0 || open >= len(src) || src[open] != '(' {
		return -1
	}
	depth := 0
	n := len(src)
	for i := open; i < n; {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i
			}
		}
		i++
	}
	return -1
}

// skipCommentOrQuoted behaves like skipCommentOrString but leaves backtick
// identifiers alone, because a caller scanning to the next token must be able
// to read them.
func skipCommentOrQuoted(src string, i int) (int, bool) {
	if i < len(src) && src[i] == '`' {
		return i, false
	}
	return skipCommentOrString(src, i)
}

func skipWhitespaceAndComments(src string, i int) int {
	n := len(src)
	for i < n {
		if src[i] == ' ' || src[i] == '\t' || src[i] == '\r' || src[i] == '\n' {
			i++
			continue
		}
		next, _ := skipCommentOrQuoted(src, i)
		if next != i {
			i = next
			continue
		}
		break
	}
	return i
}

func isIdentStart(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' || c == '$'
}

func isIdentPart(c byte) bool {
	return isIdentStart(c) || (c >= '0' && c <= '9')
}

// readIdent reads an identifier or backtick identifier from start.
func readIdent(src string, start int) (string, string, int) {
	n := len(src)
	if start >= n {
		return "", "", start
	}
	if src[start] == '`' {
		j := start + 1
		for j < n && src[j] != '`' && src[j] != '\n' {
			j++
		}
		raw := src[start:j]
		name := src[start+1 : j]
		if j < n && src[j] == '`' {
			j++
			raw = src[start:j]
		}
		return raw, name, j
	}
	if isIdentStart(src[start]) {
		j := start + 1
		for j < n && isIdentPart(src[j]) {
			j++
		}
		return src[start:j], src[start:j], j
	}
	return "", "", start
}

type scopeEntry struct {
	name      string
	braceOpen int
}

func buildScope(stack []scopeEntry) string {
	if len(stack) == 0 {
		return ""
	}
	var names []string
	for _, s := range stack {
		names = append(names, s.name)
	}
	return strings.Join(names, " > ")
}

// SwiftAttribute represents an attribute before a function or type (@Test, @MainActor, etc.).
type SwiftAttribute struct {
	Name     string
	Raw      string
	Disabled bool
}

// parseSwiftAttributes parses attributes (@...) between start and end.
func parseSwiftAttributes(src string, start, end int) []SwiftAttribute {
	var attrs []SwiftAttribute
	i := start
	for i < end {
		i = skipWhitespaceAndComments(src, i)
		if i >= end {
			break
		}
		if src[i] == '@' {
			attrStart := i
			i++
			nameStart := i
			for i < end && isIdentPart(src[i]) {
				i++
			}
			attrName := src[nameStart:i]

			hasArgs := false
			argsContent := ""
			k := skipWhitespaceAndComments(src, i)
			if k < end && src[k] == '(' {
				closingParen := findMatchingParen(src, k)
				if closingParen != -1 && closingParen <= end {
					hasArgs = true
					argsContent = src[k+1 : closingParen]
					i = closingParen + 1
				}
			}

			attr := SwiftAttribute{
				Name: attrName,
				Raw:  src[attrStart:i],
			}
			if attrName == "Test" && hasArgs && strings.Contains(argsContent, ".disabled") {
				attr.Disabled = true
			}
			attrs = append(attrs, attr)
			continue
		}
		i++
	}
	return attrs
}

func findSwiftAttrStart(src string, funcOffset int) int {
	i := funcOffset - 1
	lastGood := funcOffset
	for i >= 0 {
		// A standalone line comment above the declaration must be stepped over
		// whole; its text can otherwise be mistaken for an attribute, which
		// would make the next real test look disabled.
		if src[i] == '\n' {
			lineStart := strings.LastIndexByte(src[:i], '\n') + 1
			if trimmed := strings.TrimSpace(src[lineStart:i]); strings.HasPrefix(trimmed, "//") {
				i = lineStart - 1
				continue
			}
			i--
			continue
		}
		if src[i] == ' ' || src[i] == '\t' || src[i] == '\r' {
			i--
			continue
		}
		if src[i] == ')' {
			open := findMatchingParenRev(src, i)
			if open >= 0 {
				i = open - 1
				continue
			}
		}
		if src[i] == '@' {
			lastGood = i
			i--
			continue
		}
		if isIdentPart(src[i]) {
			j := i
			for j >= 0 && isIdentPart(src[j]) {
				j--
			}
			k := j
			for k >= 0 && (src[k] == ' ' || src[k] == '\t' || src[k] == '\r' || src[k] == '\n') {
				k--
			}
			if k >= 0 && src[k] == '@' {
				lastGood = k
				i = k - 1
				continue
			}
			word := src[j+1 : i+1]
			if isSwiftModifier(word) {
				lastGood = j + 1
				i = j
				continue
			}
			break
		}
		break
	}
	return lastGood
}

func isSwiftModifier(w string) bool {
	switch w {
	case "public", "private", "fileprivate", "internal", "open", "override", "final", "static", "class", "mutating", "nonmutating", "async", "throws", "rethrows":
		return true
	}
	return false
}

func findMatchingParenRev(src string, closeIdx int) int {
	depth := 0
	for i := closeIdx; i >= 0; i-- {
		if src[i] == ')' {
			depth++
		} else if src[i] == '(' {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

// isFirstStatementXCTSkip checks if the first statement in the body is `throw XCTSkip(`.
func isFirstStatementXCTSkip(body string) bool {
	n := len(body)
	i := skipWhitespaceAndComments(body, 0)
	if i >= n {
		return false
	}
	if strings.HasPrefix(body[i:], "throw") && (i == 0 || !isIdentPart(body[i-1])) {
		j := skipWhitespaceAndComments(body, i+5)
		if strings.HasPrefix(body[j:], "XCTSkip") {
			k := skipWhitespaceAndComments(body, j+7)
			if k < n && body[k] == '(' {
				return true
			}
		}
	}
	return false
}

func parseSwiftUnits(src string, lineOffsets []int, filePath string, helperMap map[string]bool) []parser.TestUnit {
	var units []parser.TestUnit
	n := len(src)
	var scopeStack []scopeEntry

	for i := 0; i < n; {
		next := skipCommentsAndStrings(src, i)
		if next != i {
			i = next
			continue
		}

		// Scope exit: }
		if src[i] == '}' {
			if len(scopeStack) > 0 {
				scopeStack = scopeStack[:len(scopeStack)-1]
			}
			i++
			continue
		}

		// Types: class, struct, extension, enum, actor
		// or @Suite struct ...
		isTypeDecl := false
		var typeKeywordLen int
		if strings.HasPrefix(src[i:], "class ") && (i == 0 || !isIdentPart(src[i-1])) {
			isTypeDecl = true
			typeKeywordLen = 6
		} else if strings.HasPrefix(src[i:], "struct ") && (i == 0 || !isIdentPart(src[i-1])) {
			isTypeDecl = true
			typeKeywordLen = 7
		} else if strings.HasPrefix(src[i:], "extension ") && (i == 0 || !isIdentPart(src[i-1])) {
			isTypeDecl = true
			typeKeywordLen = 10
		} else if strings.HasPrefix(src[i:], "enum ") && (i == 0 || !isIdentPart(src[i-1])) {
			isTypeDecl = true
			typeKeywordLen = 5
		} else if strings.HasPrefix(src[i:], "actor ") && (i == 0 || !isIdentPart(src[i-1])) {
			isTypeDecl = true
			typeKeywordLen = 6
		}

		if isTypeDecl {
			j := skipWhitespaceAndComments(src, i+typeKeywordLen)
			_, typeName, endIdent := readIdent(src, j)
			if typeName != "" {
				// Find {
				k := endIdent
				for k < n && src[k] != '{' && src[k] != ';' {
					nextK := skipCommentsAndStrings(src, k)
					if nextK != k {
						k = nextK
						continue
					}
					k++
				}
				if k < n && src[k] == '{' {
					scopeStack = append(scopeStack, scopeEntry{
						name:      typeName,
						braceOpen: k,
					})
					i = k + 1
					continue
				}
			}
		}

		// Functions: func name(...)
		if strings.HasPrefix(src[i:], "func") && (i == 0 || !isIdentPart(src[i-1])) && (i+4 >= n || !isIdentPart(src[i+4])) {
			funcOffset := i
			attrStart := findSwiftAttrStart(src, funcOffset)
			attrs := parseSwiftAttributes(src, attrStart, funcOffset)

			hasTestAttr := false
			isDisabled := false
			for _, a := range attrs {
				if a.Name == "Test" {
					hasTestAttr = true
				}
				if a.Disabled {
					isDisabled = true
				}
			}

			// Read func name
			j := skipWhitespaceAndComments(src, funcOffset+4)
			_, funcName, endIdent := readIdent(src, j)

			isXCTest := strings.HasPrefix(funcName, "test") && len(funcName) > 4 && (funcName[4] < 'a' || funcName[4] > 'z')

			if funcName != "" {
				m := skipWhitespaceAndComments(src, endIdent)
				if m < n && src[m] == '(' {
					closeParen := findMatchingParen(src, m)
					if closeParen != -1 {
						// XCTest only discovers zero-argument methods, so a
						// func named test… that takes parameters is a helper,
						// not a test. @Test functions may take arguments.
						takesParams := strings.TrimSpace(src[m+1:closeParen]) != ""
						isUnit := hasTestAttr || (isXCTest && !takesParams)
						isUnit = isUnit && !isDisabled
						// Look for opening brace {
						k := closeParen + 1
						for k < n && src[k] != '{' && src[k] != ';' {
							nextK := skipCommentsAndStrings(src, k)
							if nextK != k {
								k = nextK
								continue
							}
							k++
						}
						if k < n && src[k] == '{' {
							closeBrace := findMatchingBrace(src, k)
							if closeBrace != -1 {
								body := src[k+1 : closeBrace]
								// Check first statement for throw XCTSkip(
								if isUnit && !isFirstStatementXCTSkip(body) {
									startLine := lineFromOffset(lineOffsets, funcOffset)
									endLine := lineFromOffset(lineOffsets, closeBrace)
									assertions := extractSwiftAssertions(body, helperMap)
									scopeStr := buildScope(scopeStack)

									units = append(units, parser.TestUnit{
										Name:       funcName,
										FilePath:   filePath,
										StartLine:  startLine,
										EndLine:    endLine,
										Kind:       "unit",
										RawBody:    body,
										Assertions: assertions,
										Scope:      scopeStr,
									})
								}
								i = closeBrace + 1
								continue
							}
						}
					}
				}
			}
		}

		i++
	}

	return units
}

func extractSwiftAssertions(body string, helperMap map[string]bool) []string {
	var assertions []string
	n := len(body)

	for i := 0; i < n; {
		next := skipCommentsAndStrings(body, i)
		if next != i {
			i = next
			continue
		}

		// Check Swift Testing macros: #expect, #require
		if body[i] == '#' {
			j := i + 1
			for j < n && isIdentPart(body[j]) {
				j++
			}
			macro := body[i:j]
			if macro == "#expect" || macro == "#require" {
				k := skipWhitespaceAndComments(body, j)
				if k < n && body[k] == '(' {
					assertions = append(assertions, macro)
					i = k + 1
					continue
				}
			}
			i = j
			continue
		}

		// Check identifiers / calls
		if isIdentStart(body[i]) || body[i] == '.' {
			isDot := false
			if body[i] == '.' {
				isDot = true
				i++
				i = skipWhitespaceAndComments(body, i)
			}
			if i < n && isIdentStart(body[i]) {
				identStart := i
				for i < n && isIdentPart(body[i]) {
					i++
				}
				ident := body[identStart:i]

				// XCTAssert..., XCTFail, XCTUnwrap, XCTExpectFailure
				if strings.HasPrefix(ident, "XCTAssert") || ident == "XCTFail" || ident == "XCTUnwrap" || ident == "XCTExpectFailure" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '\n' || body[k] == ';') {
						assertions = append(assertions, ident)
						continue
					}
				}

				// wait(for:
				if ident == "wait" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						p := skipWhitespaceAndComments(body, k+1)
						if strings.HasPrefix(body[p:], "for:") {
							assertions = append(assertions, "wait(for:")
							continue
						}
					}
				}

				// fulfillment(of:
				if ident == "fulfillment" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						p := skipWhitespaceAndComments(body, k+1)
						if strings.HasPrefix(body[p:], "of:") {
							assertions = append(assertions, "fulfillment(of:")
							continue
						}
					}
				}

				// waitForExpectations(
				if ident == "waitForExpectations" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, "waitForExpectations")
						continue
					}
				}

				// verify(
				if ident == "verify" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '{') {
						assertions = append(assertions, "verify")
						continue
					}
				}

				// assertSnapshot(
				if ident == "assertSnapshot" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, "assertSnapshot")
						continue
					}
				}

				// XCTest performance measurement: measure {, measure(, measureMetrics(
				if !isDot && (ident == "measure" || ident == "measureMetrics") {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '{' || body[k] == '(') {
						assertions = append(assertions, ident)
						continue
					}
				}
				// Nimble expect(...).to(...), etc.
				if ident == "expect" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, "expect")
						continue
					}
				}

				// member form .assert...(
				if isDot && strings.HasPrefix(ident, "assert") {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, "."+ident)
						continue
					}
				}

				// helper call
				if helperMap != nil && helperMap[ident] {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '{') {
						assertions = append(assertions, ident)
						continue
					}
				}
			}
			continue
		}

		i++
	}

	return dedupeStrings(assertions)
}

func dedupeStrings(in []string) []string {
	if len(in) == 0 {
		return in
	}
	seen := make(map[string]bool)
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func findAssertingHelpers(src string) map[string]bool {
	helpers := make(map[string]bool)
	n := len(src)

	for i := 0; i < n; {
		next := skipCommentsAndStrings(src, i)
		if next != i {
			i = next
			continue
		}

		if strings.HasPrefix(src[i:], "func") && (i == 0 || !isIdentPart(src[i-1])) && (i+4 >= n || !isIdentPart(src[i+4])) {
			funcOffset := i
			attrStart := findSwiftAttrStart(src, funcOffset)
			attrs := parseSwiftAttributes(src, attrStart, funcOffset)

			hasTestAttr := false
			for _, a := range attrs {
				if a.Name == "Test" {
					hasTestAttr = true
					break
				}
			}

			j := skipWhitespaceAndComments(src, funcOffset+4)
			_, funcName, endIdent := readIdent(src, j)

			isXCTest := strings.HasPrefix(funcName, "test") && len(funcName) > 4 && (funcName[4] < 'a' || funcName[4] > 'z')
			isTest := hasTestAttr

			if !isTest && funcName != "" {
				m := skipWhitespaceAndComments(src, endIdent)
				if m < n && src[m] == '(' {
					closeParen := findMatchingParen(src, m)
					if closeParen != -1 {
						// A func named test… that takes parameters cannot be
						// discovered by XCTest, so it may assert as a helper.
						if isXCTest && strings.TrimSpace(src[m+1:closeParen]) == "" {
							isTest = true
						}
					}
				}
			}

			if !isTest && funcName != "" {
				m := skipWhitespaceAndComments(src, endIdent)
				if m < n && src[m] == '(' {
					closeParen := findMatchingParen(src, m)
					if closeParen != -1 {
						k := closeParen + 1
						for k < n && src[k] != '{' && src[k] != ';' {
							nextK := skipCommentsAndStrings(src, k)
							if nextK != k {
								k = nextK
								continue
							}
							k++
						}
						if k < n && src[k] == '{' {
							closeBrace := findMatchingBrace(src, k)
							if closeBrace != -1 {
								body := src[k+1 : closeBrace]
								as := extractSwiftAssertions(body, nil)
								if len(as) > 0 {
									helpers[funcName] = true
								}
								i = closeBrace + 1
								continue
							}
						}
					}
				}
			}
		}

		i++
	}

	return helpers
}
