// Package kotlin provides a LanguageAdapter implementation for Kotlin test files.
package kotlin

import (
	"fmt"
	"strings"

	"github.com/HoangNguyen0403/testguard/pkg/parser"
)

// Adapter implements parser.LanguageAdapter for Kotlin files (.kt).
type Adapter struct{}

// NewAdapter creates and returns a new Kotlin LanguageAdapter.
func NewAdapter() *Adapter {
	return &Adapter{}
}

// ID returns the language identifier "kotlin".
func (a *Adapter) ID() string {
	return "kotlin"
}

// FileExtensions returns the file extensions handled by this adapter.
func (a *Adapter) FileExtensions() []string {
	return []string{".kt"}
}

// IsGenerated returns true if the file header indicates generated code.
func (a *Adapter) IsGenerated(filePath string, header []byte) bool {
	headerStr := strings.ToLower(string(header))
	return strings.Contains(headerStr, "generated by") ||
		strings.Contains(headerStr, "@generated") ||
		strings.Contains(headerStr, "do not edit")
}

// LocateTests parses a Kotlin source file and returns the list of detected test units.
// Input whose comments, strings, or brackets are lexically unbalanced is rejected
// with an error so the caller reports a parse failure instead of a partial scan.
func (a *Adapter) LocateTests(source []byte, filePath string) ([]parser.TestUnit, error) {
	src := string(source)
	if err := validateLexicalStructure(src); err != nil {
		return nil, err
	}
	lines := strings.Split(src, "\n")
	lineOffsets := computeLineOffsets(lines)

	// Step 1: Discover helpers in the file that contain assertions
	helperMap := findAssertingHelpers(src)

	// Step 2: Parse test units
	units := parseKotlinUnits(src, lineOffsets, filePath, helperMap)

	return units, nil
}

func computeLineOffsets(lines []string) []int {
	offsets := make([]int, len(lines))
	curr := 0
	for i, l := range lines {
		offsets[i] = curr
		curr += len(l) + 1 // +1 for '\n'
	}
	return offsets
}

func lineFromOffset(offsets []int, offset int) int {
	low, high := 0, len(offsets)-1
	result := 0
	for low <= high {
		mid := (low + high) / 2
		if offsets[mid] <= offset {
			result = mid
			low = mid + 1
		} else {
			high = mid - 1
		}
	}
	return result + 1 // 1-based
}

// skipCommentOrString advances past the comment, string, or backtick identifier
// that starts at src[i]. It reports the offset just past the construct and
// whether that construct was terminated; a false-termination result is how
// LocateTests distinguishes an unterminated construct from ordinary code. It
// returns (i, false) when src[i] starts none of them.
func skipCommentOrString(src string, i int) (int, bool) {
	n := len(src)
	if i >= n {
		return i, false
	}

	// Line comment: //
	if i+1 < n && src[i] == '/' && src[i+1] == '/' {
		j := i + 2
		for j < n && src[j] != '\n' {
			j++
		}
		return j, true
	}

	// Block comment: /* ... */ (nestable in Kotlin)
	if i+1 < n && src[i] == '/' && src[i+1] == '*' {
		j := i + 2
		depth := 1
		for j < n {
			if j+1 < n && src[j] == '/' && src[j+1] == '*' {
				depth++
				j += 2
				continue
			}
			if j+1 < n && src[j] == '*' && src[j+1] == '/' {
				depth--
				j += 2
				if depth == 0 {
					return j, true
				}
				continue
			}
			j++
		}
		return n, false
	}

	// Backtick identifier: `name` may contain braces and quotes.
	if src[i] == '`' {
		j := i + 1
		for j < n && src[j] != '`' && src[j] != '\n' {
			j++
		}
		if j < n && src[j] == '`' {
			return j + 1, true
		}
		return j, false
	}

	// Char literal: '...'
	if src[i] == '\'' {
		j := i + 1
		for j < n {
			if src[j] == '\\' {
				j += 2
				continue
			}
			if src[j] == '\'' {
				return j + 1, true
			}
			if src[j] == '\n' {
				return j, false
			}
			j++
		}
		return n, false
	}

	if src[i] == '"' {
		return skipStringLiteral(src, i)
	}

	return i, false
}

// skipStringLiteral advances past a Kotlin string literal, honouring escapes,
// triple-quoted text, and ${...} templates whose expressions may themselves
// contain strings, comments, and braces.
func skipStringLiteral(src string, i int) (int, bool) {
	n := len(src)
	triple := i+2 < n && src[i+1] == '"' && src[i+2] == '"'
	j := i + 1
	if triple {
		j = i + 3
	}
	for j < n {
		if !triple && src[j] == '\\' {
			j += 2
			continue
		}
		if src[j] == '$' && j+1 < n {
			if src[j+1] == '{' {
				j = skipTemplateExpression(src, j+1)
				continue
			}
			if isIdentStart(src[j+1]) {
				j += 2
				for j < n && isIdentPart(src[j]) {
					j++
				}
				continue
			}
		}
		if triple {
			if src[j] == '"' {
				// A raw string closes on the trailing three quotes of a
				// maximal quote run; any surplus quotes are content (a quoted
				// fragment or regex ending in a quote). Ending at the first
				// three would leave the surplus to open a new, unterminated
				// string.
				k := j
				for k < n && src[k] == '"' {
					k++
				}
				if k-j >= 3 {
					return k, true
				}
				j = k
				continue
			}
		} else {
			if src[j] == '"' {
				return j + 1, true
			}
			if src[j] == '\n' {
				return j, false
			}
		}
		j++
	}
	return n, false
}

// skipTemplateExpression advances past the ${...} template expression whose
// opening brace is src[i], scanning nested strings and comments so braces that
// belong to them do not end the template early.
func skipTemplateExpression(src string, i int) int {
	n := len(src)
	depth := 0
	for i < n {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return i + 1
			}
		}
		i++
	}
	return n
}

// skipCommentsAndStrings advances index i past any comment or string literal starting at src[i].
func skipCommentsAndStrings(src string, i int) int {
	end, _ := skipCommentOrString(src, i)
	return end
}

// validateLexicalStructure rejects a file whose comments, strings, or bracket
// delimiters are unbalanced. TestGuard scans Kotlin lexically rather than with
// a full grammar, so this bound is what lets LocateTests fail closed instead of
// reporting a truncated unit list as a complete scan. Angle brackets and
// language constructs outside comments, strings, and brackets are not checked.
func validateLexicalStructure(src string) error {
	var stack []byte
	n := len(src)
	for i := 0; i < n; {
		if next, ok := skipCommentOrString(src, i); next != i {
			if !ok {
				return fmt.Errorf("kotlin: unterminated comment or string literal at offset %d", i)
			}
			i = next
			continue
		}
		switch src[i] {
		case '(', '[', '{':
			stack = append(stack, src[i])
		case ')', ']', '}':
			if len(stack) == 0 {
				return fmt.Errorf("kotlin: unexpected %q at offset %d", src[i], i)
			}
			open := stack[len(stack)-1]
			if (open == '(' && src[i] != ')') || (open == '[' && src[i] != ']') || (open == '{' && src[i] != '}') {
				return fmt.Errorf("kotlin: %q closes %q at offset %d", src[i], open, i)
			}
			stack = stack[:len(stack)-1]
		}
		i++
	}
	if len(stack) > 0 {
		return fmt.Errorf("kotlin: %d unclosed delimiter(s) at end of file", len(stack))
	}
	return nil
}

// findMatchingBrace returns the index of the '}' that closes the '{' at open,
// skipping comments, strings, and templates; it returns -1 when unmatched.
func findMatchingBrace(src string, open int) int {
	if open < 0 || open >= len(src) || src[open] != '{' {
		return -1
	}
	depth := 0
	n := len(src)
	for i := open; i < n; {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return i
			}
		}
		i++
	}
	return -1
}

// findMatchingParen returns the index of the ')' that closes the '(' at open,
// skipping comments, strings, and templates; it returns -1 when unmatched.
func findMatchingParen(src string, open int) int {
	if open < 0 || open >= len(src) || src[open] != '(' {
		return -1
	}
	depth := 0
	n := len(src)
	for i := open; i < n; {
		if next, _ := skipCommentOrString(src, i); next != i {
			i = next
			continue
		}
		switch src[i] {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return i
			}
		}
		i++
	}
	return -1
}

// skipCommentOrQuoted behaves like skipCommentOrString but leaves backtick
// identifiers alone, because a caller scanning to the next token must be able
// to read them.
func skipCommentOrQuoted(src string, i int) (int, bool) {
	if i < len(src) && src[i] == '`' {
		return i, false
	}
	return skipCommentOrString(src, i)
}

func skipWhitespaceAndComments(src string, i int) int {
	n := len(src)
	for i < n {
		if src[i] == ' ' || src[i] == '\t' || src[i] == '\r' || src[i] == '\n' {
			i++
			continue
		}
		next, _ := skipCommentOrQuoted(src, i)
		if next != i {
			i = next
			continue
		}
		break
	}
	return i
}

func isIdentStart(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_'
}

func isIdentPart(c byte) bool {
	return isIdentStart(c) || (c >= '0' && c <= '9')
}

// readIdent reads an identifier or backtick identifier from start.
// Returns the raw string, the unescaped name, and the end index.
func readIdent(src string, start int) (string, string, int) {
	n := len(src)
	if start >= n {
		return "", "", start
	}
	if src[start] == '`' {
		// Backtick identifier
		j := start + 1
		for j < n && src[j] != '`' && src[j] != '\n' {
			j++
		}
		raw := src[start:j]
		name := src[start+1 : j]
		if j < n && src[j] == '`' {
			j++
			raw = src[start:j]
		}
		return raw, name, j
	}
	if isIdentStart(src[start]) {
		j := start + 1
		for j < n && isIdentPart(src[j]) {
			j++
		}
		return src[start:j], src[start:j], j
	}
	return "", "", start
}

// Annotation represents a Kotlin annotation before a function.
type Annotation struct {
	Name     string
	Raw      string
	Expected bool
	Ignored  bool
}

// parseAnnotationsBeforeFun parses any annotations between lastToken and funOffset.
func parseAnnotationsBeforeFun(src string, start, end int) []Annotation {
	var annos []Annotation
	i := start
	for i < end {
		i = skipWhitespaceAndComments(src, i)
		if i >= end {
			break
		}
		if src[i] == '@' {
			annoStart := i
			i++ // skip '@'
			if i < end && src[i] == '[' {
				// @[...] syntax in Kotlin
				// Skip bracket for simplicity or parse inside
				i++
			}
			// Read annotation identifier
			nameStart := i
			for i < end && (isIdentPart(src[i]) || src[i] == '.') {
				i++
			}
			annoName := src[nameStart:i]
			// Short name without package
			shortName := annoName
			if dot := strings.LastIndex(annoName, "."); dot >= 0 {
				shortName = annoName[dot+1:]
			}

			// Check for argument list: (...)
			hasArgs := false
			argsContent := ""
			k := skipWhitespaceAndComments(src, i)
			if k < end && src[k] == '(' {
				closingParen := findMatchingParen(src, k)
				if closingParen != -1 && closingParen <= end {
					hasArgs = true
					argsContent = src[k+1 : closingParen]
					i = closingParen + 1
				}
			}

			anno := Annotation{
				Name: shortName,
				Raw:  src[annoStart:i],
			}
			if shortName == "Ignore" || shortName == "Disabled" {
				anno.Ignored = true
			}
			if shortName == "Test" && hasArgs && strings.Contains(argsContent, "expected") {
				anno.Expected = true
			}
			annos = append(annos, anno)
			continue
		}
		i++
	}
	return annos
}

type scopeEntry struct {
	name      string
	braceOpen int
}

func parseKotlinUnits(src string, lineOffsets []int, filePath string, helperMap map[string]bool) []parser.TestUnit {
	var units []parser.TestUnit
	n := len(src)

	var scopeStack []scopeEntry

	for i := 0; i < n; {
		next := skipCommentsAndStrings(src, i)
		if next != i {
			i = next
			continue
		}

		// Check scope exit
		if src[i] == '}' {
			if len(scopeStack) > 0 && scopeStack[len(scopeStack)-1].braceOpen != -1 {
				scopeStack = scopeStack[:len(scopeStack)-1]
			}
			i++
			continue
		}

		// Check class declaration: class Foo, interface Foo, object Foo
		if (strings.HasPrefix(src[i:], "class ") || strings.HasPrefix(src[i:], "object ") || strings.HasPrefix(src[i:], "interface ")) &&
			(i == 0 || !isIdentPart(src[i-1])) {
			// Find class name
			var wordLen int
			if src[i] == 'c' {
				wordLen = 6
			} else if src[i] == 'o' {
				wordLen = 7
			} else {
				wordLen = 10
			}
			j := skipWhitespaceAndComments(src, i+wordLen)
			_, className, endIdent := readIdent(src, j)
			if className != "" {
				// Find opening brace of class
				k := endIdent
				for k < n && src[k] != '{' && src[k] != ';' {
					nextK := skipCommentsAndStrings(src, k)
					if nextK != k {
						k = nextK
						continue
					}
					k++
				}
				if k < n && src[k] == '{' {
					scopeStack = append(scopeStack, scopeEntry{
						name:      className,
						braceOpen: k,
					})
					i = k + 1
					continue
				}
			}
		}

		// Check Kotest styles: test("..."), it("..."), should("...")
		// e.g. test("name") { ... }
		kotestKind := ""
		if strings.HasPrefix(src[i:], "test") && (i == 0 || !isIdentPart(src[i-1])) {
			kotestKind = "test"
		} else if strings.HasPrefix(src[i:], "it") && (i == 0 || !isIdentPart(src[i-1])) {
			kotestKind = "it"
		} else if strings.HasPrefix(src[i:], "should") && (i == 0 || !isIdentPart(src[i-1])) {
			kotestKind = "should"
		}

		if kotestKind != "" {
			j := i + len(kotestKind)
			j = skipWhitespaceAndComments(src, j)
			if j < n && src[j] == '(' {
				closingParen := findMatchingParen(src, j)
				if closingParen != -1 {
					k := skipWhitespaceAndComments(src, closingParen+1)
					if k < n && src[k] == '{' {
						closingBrace := findMatchingBrace(src, k)
						if closingBrace != -1 {
							// Extract test title from within parentheses
							parenContent := strings.TrimSpace(src[j+1 : closingParen])
							// If quoted string, trim quotes
							title := parenContent
							if strings.HasPrefix(title, "\"") && strings.HasSuffix(title, "\"") && len(title) >= 2 {
								title = title[1 : len(title)-1]
							}

							body := src[k+1 : closingBrace]
							startLine := lineFromOffset(lineOffsets, i)
							endLine := lineFromOffset(lineOffsets, closingBrace)

							assertions := extractAssertions(body, helperMap, false)

							scopeStr := buildScope(scopeStack)
							units = append(units, parser.TestUnit{
								Name:       title,
								FilePath:   filePath,
								StartLine:  startLine,
								EndLine:    endLine,
								Kind:       "unit",
								RawBody:    body,
								Assertions: assertions,
								Scope:      scopeStr,
							})

							i = closingBrace + 1
							continue
						}
					}
				}
			}
		}

		// Check fun declaration: fun name(...) ...
		if strings.HasPrefix(src[i:], "fun") && (i == 0 || !isIdentPart(src[i-1])) && (i+3 >= n || !isIdentPart(src[i+3])) {
			funOffset := i
			// Look backwards to find annotations
			annoStart := findAnnotationStart(src, funOffset)
			annos := parseAnnotationsBeforeFun(src, annoStart, funOffset)

			isTest := false
			isIgnored := false
			hasExpected := false

			for _, a := range annos {
				if a.Ignored {
					isIgnored = true
				}
				if a.Name == "Test" || a.Name == "ParameterizedTest" || a.Name == "RepeatedTest" {
					isTest = true
				}
				if a.Expected {
					hasExpected = true
				}
			}

			// Read fun name
			j := skipWhitespaceAndComments(src, funOffset+3)
			// Might be generic: fun <T> name
			if j < n && src[j] == '<' {
				k := findMatchingAngle(src, j)
				if k != -1 {
					j = skipWhitespaceAndComments(src, k+1)
				}
			}
			// Might have receiver: fun Receiver.name
			// We can read ident; if followed by '.', read next ident
			_, funName, endIdent := readIdent(src, j)
			k := skipWhitespaceAndComments(src, endIdent)
			if k < n && src[k] == '.' {
				k = skipWhitespaceAndComments(src, k+1)
				_, funName2, endIdent2 := readIdent(src, k)
				if funName2 != "" {
					funName = funName2
					endIdent = endIdent2
				}
			}

			if funName != "" {
				m := skipWhitespaceAndComments(src, endIdent)
				if m < n && src[m] == '(' {
					closeParen := findMatchingParen(src, m)
					if closeParen != -1 {
						p := skipWhitespaceAndComments(src, closeParen+1)
						if p < n && src[p] == ':' {
							p = skipTypeOrModifiers(src, p+1)
						}

						if p < n && src[p] == '{' {
							closeBrace := findMatchingBrace(src, p)
							if closeBrace != -1 {
								if isTest && !isIgnored {
									body := src[p+1 : closeBrace]
									startLine := lineFromOffset(lineOffsets, funOffset)
									endLine := lineFromOffset(lineOffsets, closeBrace)
									assertions := extractAssertions(body, helperMap, hasExpected)
									scopeStr := buildScope(scopeStack)

									meta := make(map[string]string)
									if strings.Contains(src, "StandardTestDispatcher") {
										meta["hasStandardDispatcher"] = "true"
									}
									if strings.Contains(src, "UnconfinedTestDispatcher") {
										meta["hasUnconfinedDispatcher"] = "true"
									}
									units = append(units, parser.TestUnit{
										Name:       funName,
										FilePath:   filePath,
										StartLine:  startLine,
										EndLine:    endLine,
										Kind:       "unit",
										RawBody:    body,
										Assertions: assertions,
										Scope:      scopeStr,
										Meta:       meta,
									})
								}
								i = closeBrace + 1
								continue
							}
						} else if p < n && src[p] == '=' {
							pEq := skipWhitespaceAndComments(src, p+1)
							bodyStart := pEq
							bodyEnd := -1
							for q := pEq; q < n; {
								nextQ := skipCommentsAndStrings(src, q)
								if nextQ != q {
									q = nextQ
									continue
								}
								if src[q] == '{' {
									cb := findMatchingBrace(src, q)
									if cb != -1 {
										bodyEnd = cb + 1
										break
									}
								}
								if src[q] == '\n' {
									bodyEnd = q
									break
								}
								q++
							}
							if bodyEnd == -1 {
								bodyEnd = n
							}
							if isTest && !isIgnored {
								body := src[bodyStart:bodyEnd]
								startLine := lineFromOffset(lineOffsets, funOffset)
								endLine := lineFromOffset(lineOffsets, bodyEnd)
								assertions := extractAssertions(body, helperMap, hasExpected)
								scopeStr := buildScope(scopeStack)

								meta := make(map[string]string)
								if strings.Contains(src, "StandardTestDispatcher") {
									meta["hasStandardDispatcher"] = "true"
								}
								if strings.Contains(src, "UnconfinedTestDispatcher") {
									meta["hasUnconfinedDispatcher"] = "true"
								}
								units = append(units, parser.TestUnit{
									Name:       funName,
									FilePath:   filePath,
									StartLine:  startLine,
									EndLine:    endLine,
									Kind:       "unit",
									RawBody:    body,
									Assertions: assertions,
									Scope:      scopeStr,
									Meta:       meta,
								})
							}
							i = bodyEnd
							continue
						}
					}
				}
			}
		}

		i++
	}

	return units
}

func buildScope(stack []scopeEntry) string {
	if len(stack) == 0 {
		return ""
	}
	var names []string
	for _, s := range stack {
		names = append(names, s.name)
	}
	return strings.Join(names, " > ")
}

// findAnnotationStart searches backwards from funOffset to find where the annotations start.
func findAnnotationStart(src string, funOffset int) int {
	i := funOffset - 1
	lastGood := funOffset
	for i >= 0 {
		// A standalone line comment above the declaration must be stepped over
		// whole; its text can otherwise be mistaken for an annotation, which
		// would make the next real test look ignored or disabled.
		if src[i] == '\n' {
			lineStart := strings.LastIndexByte(src[:i], '\n') + 1
			if trimmed := strings.TrimSpace(src[lineStart:i]); strings.HasPrefix(trimmed, "//") {
				i = lineStart - 1
				continue
			}
			i--
			continue
		}
		// If newline or whitespace
		if src[i] == ' ' || src[i] == '\t' || src[i] == '\r' {
			i--
			continue
		}
		// Check if inside closing paren or bracket of annotation
		if src[i] == ')' || src[i] == ']' {
			// Find opening
			open := findMatchingParenOrBracketRev(src, i)
			if open >= 0 {
				i = open - 1
				continue
			}
		}
		if src[i] == '@' {
			lastGood = i
			i--
			continue
		}
		if isIdentPart(src[i]) || src[i] == '.' {
			// Identifier part (could be annotation name or modifier like private/internal/open)
			j := i
			for j >= 0 && (isIdentPart(src[j]) || src[j] == '.') {
				j--
			}
			// Look right before j
			k := j
			for k >= 0 && (src[k] == ' ' || src[k] == '\t' || src[k] == '\r' || src[k] == '\n') {
				k--
			}
			if k >= 0 && src[k] == '@' {
				lastGood = k
				i = k - 1
				continue
			}
			// Modifiers like suspend, inline, internal, public, private
			word := src[j+1 : i+1]
			if isModifier(word) {
				lastGood = j + 1
				i = j
				continue
			}
			break
		}
		break
	}
	return lastGood
}

func isModifier(w string) bool {
	switch w {
	case "public", "private", "protected", "internal", "override", "open", "final", "abstract", "suspend", "inline", "tailrec", "operator", "infix":
		return true
	}
	return false
}

func findMatchingParenOrBracketRev(src string, closeIdx int) int {
	target := src[closeIdx]
	var openTarget byte
	if target == ')' {
		openTarget = '('
	} else if target == ']' {
		openTarget = '['
	} else {
		return -1
	}

	depth := 0
	for i := closeIdx; i >= 0; i-- {
		if src[i] == target {
			depth++
		} else if src[i] == openTarget {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

func findMatchingAngle(src string, openIdx int) int {
	depth := 0
	n := len(src)
	for i := openIdx; i < n; i++ {
		if src[i] == '<' {
			depth++
		} else if src[i] == '>' {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

func skipTypeOrModifiers(src string, start int) int {
	n := len(src)
	i := start
	for i < n {
		next := skipCommentsAndStrings(src, i)
		if next != i {
			i = next
			continue
		}
		if src[i] == '{' || src[i] == '=' {
			return i
		}
		i++
	}
	return i
}

// extractAssertions scans a Kotlin test body and returns matching assertions.
func extractAssertions(body string, helperMap map[string]bool, hasExpectedException bool) []string {
	var assertions []string

	if hasExpectedException {
		assertions = append(assertions, "@Test(expected)")
	}

	// Tokenize / walk body skipping comments and strings
	n := len(body)
	for i := 0; i < n; {
		next := skipCommentsAndStrings(body, i)
		if next != i {
			i = next
			continue
		}

		// Check identifiers / calls
		if isIdentStart(body[i]) || body[i] == '.' {
			isDot := false
			if body[i] == '.' {
				isDot = true
				i++
				i = skipWhitespaceAndComments(body, i)
			}
			if i < n && isIdentStart(body[i]) {
				identStart := i
				for i < n && isIdentPart(body[i]) {
					i++
				}
				ident := body[identStart:i]

				// Check Kotest should... infix or method call
				if strings.HasPrefix(ident, "should") {
					// Kotest matcher e.g. shouldBe, shouldEqual, shouldThrow<...
					// If followed by '(', '<', or space (infix)
					assertions = append(assertions, ident)
					continue
				}

				// Check contract call `check(...) { … }`, with or without a
				// receiver: it throws on a false condition, so it verifies
				// behaviour the same way a dotted member call does.
				if ident == "check" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '{') {
						if isDot {
							assertions = append(assertions, ".check")
						} else {
							assertions = append(assertions, "check")
						}
						continue
					}
				}

				// Check .assert<Upper...> or assert<Upper...>
				if strings.HasPrefix(ident, "assert") {
					k := skipWhitespaceAndComments(body, i)
					// Could be assert(, assertThat(, assertEquals(, assertFailsWith<...>(
					if k < n && (body[k] == '(' || body[k] == '<' || body[k] == '{') {
						if isDot {
							assertions = append(assertions, "."+ident)
						} else {
							assertions = append(assertions, ident)
						}
						continue
					}
				}

				// Check verify / coVerify / verifyOrder / etc.
				if strings.HasPrefix(ident, "verify") || ident == "coVerify" || ident == "confirmVerified" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '{' || body[k] == '(') {
						assertions = append(assertions, ident)
						continue
					}
				}

				// Check expectThat, expectCatching, expect {
				if ident == "expectThat" || ident == "expectCatching" || ident == "expect" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '{') {
						assertions = append(assertions, ident)
						continue
					}
				}

				// Check fail(
				if ident == "fail" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, "fail")
						continue
					}
				}

				// Check Turbine: awaitError(), awaitComplete(), expectNoEvents()
				if ident == "awaitError" || ident == "awaitComplete" || ident == "expectNoEvents" {
					k := skipWhitespaceAndComments(body, i)
					if k < n && body[k] == '(' {
						assertions = append(assertions, ident)
						continue
					}
				}

				// Check same-file helper call
				if helperMap != nil && helperMap[ident] {
					k := skipWhitespaceAndComments(body, i)
					if k < n && (body[k] == '(' || body[k] == '{') {
						assertions = append(assertions, ident)
						continue
					}
				}
			}
			continue
		}

		i++
	}

	return dedupeStrings(assertions)
}

func dedupeStrings(in []string) []string {
	if len(in) == 0 {
		return in
	}
	seen := make(map[string]bool)
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// findAssertingHelpers scans the whole file for helper functions (not tests) that contain assertions.
func findAssertingHelpers(src string) map[string]bool {
	helpers := make(map[string]bool)
	n := len(src)

	// We pass empty helper map so direct assertions are detected
	for i := 0; i < n; {
		next := skipCommentsAndStrings(src, i)
		if next != i {
			i = next
			continue
		}

		if strings.HasPrefix(src[i:], "fun") && (i == 0 || !isIdentPart(src[i-1])) && (i+3 >= n || !isIdentPart(src[i+3])) {
			funOffset := i
			annoStart := findAnnotationStart(src, funOffset)
			annos := parseAnnotationsBeforeFun(src, annoStart, funOffset)

			isTest := false
			for _, a := range annos {
				if a.Name == "Test" || a.Name == "ParameterizedTest" || a.Name == "RepeatedTest" {
					isTest = true
					break
				}
			}

			// Read fun name
			j := skipWhitespaceAndComments(src, funOffset+3)
			if j < n && src[j] == '<' {
				k := findMatchingAngle(src, j)
				if k != -1 {
					j = skipWhitespaceAndComments(src, k+1)
				}
			}
			_, funName, endIdent := readIdent(src, j)

			if !isTest && funName != "" {
				// Parse body
				m := skipWhitespaceAndComments(src, endIdent)
				if m < n && src[m] == '(' {
					closeParen := findMatchingParen(src, m)
					if closeParen != -1 {
						p := skipWhitespaceAndComments(src, closeParen+1)
						if p < n && src[p] == ':' {
							p = skipTypeOrModifiers(src, p+1)
						}
						if p < n && src[p] == '{' {
							closeBrace := findMatchingBrace(src, p)
							if closeBrace != -1 {
								body := src[p+1 : closeBrace]
								as := extractAssertions(body, nil, false)
								if len(as) > 0 {
									helpers[funName] = true
								}
								i = closeBrace + 1
								continue
							}
						}
					}
				}
			}
		}

		i++
	}

	return helpers
}
